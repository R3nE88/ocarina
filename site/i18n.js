let LANG = (() => {
  try { const saved = localStorage.getItem('ocarina-lang'); if (I18N[saved]) return saved; } catch (e) {}
  return /^es\b/i.test(navigator.language || '') ? 'es' : 'en';
})();

function t(key, vars) {
  const s = I18N[LANG][key] ?? I18N.es[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => k in vars ? vars[k] : m) : s;
}

function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-label]')) el.setAttribute('aria-label', t(el.dataset.i18nLabel));
}

// the page passes a callback to redraw whatever it builds from JS
function setLang(lang, onChange) {
  LANG = I18N[lang] ? lang : 'es';
  try { localStorage.setItem('ocarina-lang', LANG); } catch (e) {}
  applyI18n();
  onChange?.();
}
